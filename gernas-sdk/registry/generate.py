def render_attributes(reg: dict, fields: dict[str, dict], version: str) -> str:
    emitted = {n: f for n, f in fields.items() if not f.get("native")}
    out = [
        "# AUTO-GENERATED by registry/generate.py - do not edit.",
        "# Source of truth: registry/domains/*.yaml, spans.yaml, metrics.yaml, denylist.yaml",
        '"""GERNAS semantic conventions: the only permitted source of telemetry names in SDK code."""',
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        f"REGISTRY_VERSION = {version!r}",
        "",
        "",
        "class FieldSpec(NamedTuple):",
        "    key: str",
        "    domain: str",
        "    type: str",
        "    required: str",
        "    sensitivity: str",
        "    cardinality: str",
        "    action: str",
        "    enum: tuple[str, ...]",
        "",
        "",
        "class Ctx:",
        '    """Attribute keys. Blueprint §2 domains first, then component signals and SDK keys."""',
    ]
    for dom in reg["domains"]:
        rows = [f for f in dom["fields"] if not f.get("native")]
        if not rows:
            continue
        out += ["", f"    # -- {dom['domain']}{' (Blueprint §2)' if dom['blueprint'] else ''}"]
        out += [f"    {f['name']} = {f['key']!r}" for f in rows]
    out += ["", "", "class SpanName:", '    """Span names (one per GERNAS operation)."""']
    out += [f"    {s['op']} = {s['name']!r}" for s in reg["spans"]["spans"]]
    out += ["", "", "class Metric:", '    """Metric instrument names."""']
    out += [f"    {m['name']} = {m['key']!r}" for m in reg["metrics"]]
    out += ["", "", "REGISTRY: dict[str, FieldSpec] = {"]
    for f in emitted.values():
        enum = tuple(str(e) for e in f.get("enum", []) or [])
        out.append(
            f"    {f['key']!r}: FieldSpec({f['key']!r}, {f['domain']!r}, {f['type']!r}, {f['required']!r}, "
            f"{f['sensitivity']!r}, {f['cardinality']!r}, {f['action']!r}, {enum!r}),"
        )
    out.append("}")
    sp = reg["spans"]
    for const, group in (
        ("ENVELOPE", "envelope"),
        ("RUN_CONTEXT", "run_context"),
        ("RESOURCE_ATTRIBUTES", "resource"),
        ("DOCTOR_CONTEXT", "doctor_context"),
    ):
        out.append(f"{const}: tuple[str, ...] = ({', '.join('Ctx.' + n for n in sp[group])},)")
    out += [
        "",
        "# operation -> attributes required on every span of that operation (envelope excluded)",
        "REQUIRED_ATTRIBUTES: dict[str, tuple[str, ...]] = {",
    ]
    for s in sp["spans"]:
        req = ", ".join("Ctx." + n for n in s.get("required", []))
        out.append(f"    SpanName.{s['op']}: ({req}{',' if req else ''}),")
    out += ["}", "", "SPAN_KINDS: dict[str, str] = {"]
    out += [f"    SpanName.{s['op']}: {s['kind']!r}," for s in sp["spans"]]
    out += [
        "}",
        "",
        "# keys that must never be emitted (SDK redaction + Collector deletion)",
        f"DENYLIST: frozenset[str] = frozenset({_denylist(reg, fields)!r})",
    ]
    return "\n".join(out) + "\n"


def render_redaction_matrix(reg: dict, fields: dict[str, dict], version: str) -> str:
    rows = [
        {
            "field": f["key"] if not f.get("native") else f"{f['key']} (span context)",
            "domain": f["domain"],
            "sensitivity": f["sensitivity"],
            "action": f["action"],
            "cardinality": f["cardinality"],
            "collector_rule": (
                "attributes/pdpl delete"
                if f["action"] == "drop"
                else ("native span context" if f.get("native") else "redaction allow-list + value patterns")
            ),
        }
        for f in fields.values()
    ]
    rows += [
        {
            "field": d["key"],
            "domain": "denylist",
            "sensitivity": "restricted",
            "action": "drop",
            "cardinality": "unbounded",
            "collector_rule": "attributes/pdpl delete",
        }
        for d in reg["denylist"]
    ]
    doc = {"version": version, "status": "DRAFT - pending CISO / Data Governance sign-off", "fields": rows}
    return "# AUTO-GENERATED by registry/generate.py - do not edit.\n" + yaml.safe_dump(doc, sort_keys=False, width=200)


_REQ = {"always": "required", "conditional": "conditionally_required", "never": "opt_in"}


def render_semconv(reg: dict, version: str) -> str:
    groups = []
    by_name = {f["name"]: f for d in reg["domains"] for f in d["fields"]}
    for dom in reg["domains"]:
        attrs = []
        for f in dom["fields"]:
            if f.get("native"):
                continue
            a = {
                "id": f["key"],
                "type": f["type"],
                "brief": f["brief"],
                "requirement_level": _REQ[f["required"]],
                "stability": "development",
                "examples": [f["example"]] if "example" in f else [],
            }
            if f.get("enum"):
                a["type"] = {"members": [{"id": str(e), "value": str(e)} for e in f["enum"]]}
            attrs.append(a)
        groups.append(
            {
                "id": f"registry.gernas.{dom['domain']}",
                "type": "attribute_group",
                "brief": dom["brief"],
                "attributes": attrs,
            }
        )
    for s in reg["spans"]["spans"]:
        groups.append(
            {
                "id": f"span.gernas.{s['op'].lower()}",
                "type": "span",
                "span_kind": s["kind"].lower(),
                "brief": f"{s['name']} ({s['api']})",
                "attributes": [
                    {"ref": by_name[n]["key"], "requirement_level": "required"} for n in s.get("required", [])
                ],
            }
        )
    for m in reg["metrics"]:
        groups.append(
            {
                "id": f"metric.{m['key']}",
                "type": "metric",
                "metric_name": m["key"],
                "instrument": m["type"],
                "unit": m["unit"],
                "brief": m["brief"],
                "attributes": [{"ref": by_name[d]["key"]} for d in m.get("dims", [])],
            }
        )
    doc = {"schema_url": f"https://gernas.fab/schemas/{version}", "groups": groups}
    return "# AUTO-GENERATED by registry/generate.py - do not edit.\n" + yaml.safe_dump(doc, sort_keys=False, width=200)


def render_reference(reg: dict, fields: dict[str, dict], version: str) -> str:
    lines = [
        "<!-- AUTO-GENERATED by registry/generate.py - do not edit. -->",
        f"# GERNAS attribute, span and metric reference (registry {version})",
        "",
        "Blueprint §2 field names are used verbatim under the `gernas.` namespace. SDK code refers to them only",
        "through `gernas.Ctx`. `trace_id` / `span_id` are the native W3C span context.",
        "",
    ]
    for dom in reg["domains"]:
        title = "Blueprint §2 domain" if dom["blueprint"] else "SDK convention"
        lines += [
            f"## {dom['domain']} ({title}) — owner: {dom['owner']}",
            "",
            dom["brief"],
            "",
            "| Constant | Key | Type | Required | Sensitivity | Cardinality | Action | Source | Description |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for f in dom["fields"]:
            enum = f" (`{'`, `'.join(str(e) for e in f['enum'])}`)" if f.get("enum") else ""
            const = "*(span context)*" if f.get("native") else f"`Ctx.{f['name']}`"
            lines.append(
                f"| {const} | `{f['key']}` | {f['type']}{enum} | {f['required']} | {f['sensitivity']} | "
                f"{f['cardinality']} | {f['action']} | {f['source']} | {f['brief']} |"
            )
        lines.append("")
    by_name = {f["name"]: f for f in fields.values()}
    lines += [
        "## Spans",
        "",
        "| Span name | API | Kind | Required attributes (plus envelope) | Source |",
        "|---|---|---|---|---|",
    ]
    for s in reg["spans"]["spans"]:
        req = ", ".join(f"`{by_name[n]['key']}`" for n in s.get("required", []))
        lines.append(f"| `{s['name']}` | `{s['api']}` | {s['kind']} | {req} | {s['source']} |")
    env = ", ".join(f"`{by_name[n]['key']}`" for n in reg["spans"]["envelope"])
    run = ", ".join(f"`{by_name[n]['key']}`" for n in reg["spans"]["run_context"])
    lines += [
        "",
        f"Envelope on every span: {env}.",
        f"Additionally on every span inside an agent run: {run}.",
        "",
        "Events: only the OpenTelemetry standard `exception` event.",
        "",
        "## Metrics",
        "",
        "| Name | Type | Unit | Dimensions | Source | Description |",
        "|---|---|---|---|---|---|",
    ]
    for m in reg["metrics"]:
        dims = ", ".join(f"`{by_name[d]['key']}`" for d in m.get("dims", [])) or "—"
        lines.append(f"| `{m['key']}` | {m['type']} | {m['unit']} | {dims} | {m['source']} | {m['brief']} |")
    lines += ["", "## Never emitted (denylist)", ""] + [f"- `{k}`" for k in _denylist(reg, fields)]
    return "\n".join(lines) + "\n"


def _block(kind: str, items: list[str], indent: str, fmt: str) -> list[str]:
    begin, end = MARKERS[kind]
    return [indent + begin] + [indent + fmt.format(k) for k in items] + [indent + end]


def apply_blocks(text: str, blocks: dict[str, tuple[list[str], str]]) -> str:
    lines = text.splitlines()
    for kind, (items, fmt) in blocks.items():
        begin, end = MARKERS[kind]
        try:
            start = next(i for i, ln in enumerate(lines) if ln.strip() == begin)
            stop = next(i for i, ln in enumerate(lines) if ln.strip() == end)
        except StopIteration:
            continue
        indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
        lines = lines[:start] + _block(kind, items, indent, fmt) + lines[stop + 1 :]
    return "\n".join(lines) + ("\n" if text.endswith("\n") else "")


def build_outputs() -> dict[Path, str]:
    reg = load()
    fields = validate(reg)
    version = str(reg["spans"]["version"])
    allow = sorted(
        {f["key"] for f in fields.values() if f["action"] == "keep" and not f.get("native")}
        | set(reg["extra"]["allowed_keys"])
    )
    deny = _denylist(reg, fields)
    outputs = {
        ROOT / "gernas" / "attributes.py": render_attributes(reg, fields, version),
        REGISTRY / "redaction-matrix.yaml": render_redaction_matrix(reg, fields, version),
        REGISTRY / "semantic-conventions.yaml": render_semconv(reg, version),
        ROOT / "docs" / "attribute-reference.md": render_reference(reg, fields, version),
    }
    for cfg in sorted((ROOT / "collector").glob("*.yaml")):
        text = cfg.read_text(encoding="utf-8")
        if any(m[0] in text for m in MARKERS.values()):
            outputs[cfg] = apply_blocks(
                text, {"allowlist": (allow, "- {}"), "denylist": (deny, "- {{key: {}, action: delete}}")}
            )
    return outputs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any generated artefact is out of date")
    args = ap.parse_args(argv)
    try:
        outputs = build_outputs()
    except RegistryError as exc:
        print(exc, file=sys.stderr)
        return 2
    stale = [p for p, c in outputs.items() if (p.read_text(encoding="utf-8") if p.exists() else None) != c]
    if args.check:
        if stale:
            print(
                "Stale generated artefacts (run `python registry/generate.py`):\n  "
                + "\n  ".join(str(p.relative_to(ROOT)) for p in stale),
                file=sys.stderr,
            )
            return 1
        print("registry: all generated artefacts up to date")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8", newline="\n")
    print(f"registry: {len(outputs)} artefacts checked, {len(stale)} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
