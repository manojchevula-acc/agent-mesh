"""Validate the attribute registry and generate every artefact derived from it.

The registry (``registry/domains/*.yaml``, ``spans.yaml``, ``metrics.yaml``,
``denylist.yaml``) is the single source of GERNAS telemetry names. Generated:

    gernas/attributes.py                  Ctx / SpanName / Metric constants + tables
    registry/redaction-matrix.yaml        field → sensitivity → PDPL action → Collector rule
    registry/semantic-conventions.yaml    OTel-semconv-style groups for non-Python producers
    docs/attribute-reference.md           human-readable reference
    collector/*.yaml                      allow-list and denylist blocks between markers

The validator enforces the Blueprint §2 canonical context verbatim: each of the 13
blueprint domains must contain exactly the blueprint's field names.

    python registry/generate.py           # validate + write
    python registry/generate.py --check   # validate + fail if anything is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "registry"
PREFIX = "gernas."

# Blueprint §2 "The Canonical GERNAS Telemetry Context" — copied verbatim.
BLUEPRINT_CONTEXT: dict[str, set[str]] = {
    "business": {"business_domain", "use_case_id", "application_id"},
    "identity": {"user_id", "tokenized_user_id", "principal_type", "tenant", "department"},
    "agent": {"agent_id", "agent_name", "agent_version", "agent_type"},
    "execution": {"agent_run_id", "session_id", "task_id", "trace_id", "span_id"},
    "planning": {"plan_id", "step_id", "step_type", "attempt_number"},
    "tool": {"tool_id", "tool_type", "tool_version", "api_operation"},
    "ai": {"provider", "model_id", "deployment_id", "model_version"},
    "prompt": {"prompt_template_id", "prompt_version"},
    "knowledge": {"knowledge_domain", "source_id", "index_id", "retrieval_strategy"},
    "security": {"policy_id", "policy_decision", "risk_classification"},
    "infrastructure": {"cluster", "namespace", "pod", "region", "environment"},
    "cost": {"token_input", "token_output", "compute_units", "estimated_cost"},
    "outcome": {"execution_status", "business_outcome", "error_category"},
}

REQUIRED_PROPS = (
    "name",
    "key",
    "type",
    "required",
    "sensitivity",
    "cardinality",
    "rollup",
    "action",
    "source",
    "brief",
)
ENUMS = {
    "type": {"string", "int", "double", "boolean"},
    "required": {"always", "conditional", "never"},
    "sensitivity": {"public", "internal", "confidential", "restricted"},
    "cardinality": {"bounded", "growing", "unbounded"},
    "action": {"keep", "drop"},
}
SPAN_KINDS = {"INTERNAL", "SERVER", "CLIENT", "PRODUCER", "CONSUMER"}
METRIC_TYPES = {"counter", "histogram", "observable_counter"}
MARKERS = {
    "allowlist": ("# >>> GERNAS-ALLOWLIST (generated by registry/generate.py - do not edit)", "# <<< GERNAS-ALLOWLIST"),
    "denylist": ("# >>> GERNAS-DENYLIST (generated by registry/generate.py - do not edit)", "# <<< GERNAS-DENYLIST"),
}


class RegistryError(ValueError):
    pass


def load() -> dict:
    domains = []
    for path in sorted((REGISTRY / "domains").glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        doc["_file"] = path.name
        domains.append(doc)
    read = lambda name: yaml.safe_load((REGISTRY / name).read_text(encoding="utf-8"))  # noqa: E731
    return {
        "domains": domains,
        "spans": read("spans.yaml"),
        "metrics": read("metrics.yaml")["metrics"],
        "denylist": read("denylist.yaml")["denylist"],
        "extra": read("collector-allowlist-extra.yaml"),
    }


def _suffix(key: str) -> str:
    return key[len(PREFIX) :] if key.startswith(PREFIX) else key


def validate(reg: dict) -> dict[str, dict]:
    errors: list[str] = []
    fields: dict[str, dict] = {}
    keys: dict[str, str] = {}
    seen_blueprint: set[str] = set()
    for dom in reg["domains"]:
        for prop in ("domain", "blueprint", "owner", "brief", "fields"):
            if prop not in dom:
                errors.append(f"{dom['_file']}: missing domain property '{prop}'")
        name = dom.get("domain")
        if dom.get("blueprint"):
            seen_blueprint.add(name)
            expected = BLUEPRINT_CONTEXT.get(name)
            actual = {_suffix(f.get("key", "")) for f in dom.get("fields", [])}
            if expected is None:
                errors.append(f"{dom['_file']}: '{name}' is not a Blueprint §2 domain")
            elif actual != expected:
                errors.append(f"{dom['_file']}: fields {sorted(actual)} != Blueprint §2 {sorted(expected)}")
        for f in dom.get("fields", []):
            label = f"{dom['_file']}:{f.get('name', '?')}"
            for prop in REQUIRED_PROPS:
                if prop not in f:
                    errors.append(f"{label}: missing property '{prop}'")
            for prop, allowed in ENUMS.items():
                if prop in f and f[prop] not in allowed:
                    errors.append(f"{label}: {prop}={f[prop]!r} not in {sorted(allowed)}")
            if f.get("name") in fields:
                errors.append(f"{label}: duplicate constant name")
            if f.get("key") in keys:
                errors.append(f"{label}: duplicate key {f['key']} (also {keys[f['key']]})")
            if not f.get("native") and not (
                f.get("key", "").startswith(PREFIX) or f.get("key", "").startswith("http.")
            ):
                errors.append(f"{label}: key must use the '{PREFIX}' namespace")
            if f.get("cardinality") == "unbounded" and f.get("rollup"):
                errors.append(f"{label}: unbounded field cannot be a rollup dimension")
            if f.get("sensitivity") == "restricted" and f.get("action") != "drop":
                errors.append(f"{label}: restricted field must use action=drop (Blueprint §2 critical principle)")
            fields[f["name"]] = dict(f, domain=name)
            keys[f["key"]] = label
    missing = set(BLUEPRINT_CONTEXT) - seen_blueprint
    if missing:
        errors.append(f"Blueprint §2 domains missing from the registry: {sorted(missing)}")
    emitted = {n for n, f in fields.items() if not f.get("native")}
    spans = reg["spans"]
    for group in ("envelope", "run_context", "resource", "doctor_context"):
        for n in spans.get(group, []):
            if n not in emitted:
                errors.append(f"spans.yaml:{group}: unknown or native field {n}")
    ops = set()
    for s in spans["spans"]:
        if s["op"] in ops:
            errors.append(f"spans.yaml: duplicate op {s['op']}")
        ops.add(s["op"])
        if s.get("kind") not in SPAN_KINDS:
            errors.append(f"spans.yaml:{s['op']}: bad kind {s.get('kind')}")
        for n in s.get("required", []):
            if n not in emitted:
                errors.append(f"spans.yaml:{s['op']}: unknown required field {n}")
    mnames, mkeys = set(), set()
    for m in reg["metrics"]:
        if m["name"] in mnames or m["key"] in mkeys:
            errors.append(f"metrics.yaml: duplicate metric {m['name']}")
        mnames.add(m["name"])
        mkeys.add(m["key"])
        if m.get("type") not in METRIC_TYPES:
            errors.append(f"metrics.yaml:{m['name']}: bad type {m.get('type')}")
        for d in m.get("dims", []):
            if d not in emitted:
                errors.append(f"metrics.yaml:{m['name']}: unknown dimension {d}")
            elif fields[d]["cardinality"] == "unbounded":
                errors.append(f"metrics.yaml:{m['name']}: unbounded dimension {d}")
    if errors:
        raise RegistryError("Registry validation failed:\n  " + "\n  ".join(errors))
    return fields


def _denylist(reg: dict, fields: dict[str, dict]) -> list[str]:
    return sorted({f["key"] for f in fields.values() if f["action"] == "drop"} | {d["key"] for d in reg["denylist"]})


