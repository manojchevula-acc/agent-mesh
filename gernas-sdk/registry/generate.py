def render_attributes(reg: dict, fields: dict[str, dict], version: str) -> str:
    out = [
        "# AUTO-GENERATED by registry/generate.py - do not edit.",
        "# Source of truth: registry/domains/*.yaml, registry/spans.yaml, registry/metrics.yaml",
        '"""Canonical GERNAS attribute, span and metric names (the only permitted way to',
        'reference them in SDK code - see tests/test_no_handtyped_attrs.py)."""',
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        f"REGISTRY_VERSION = {version!r}",
        "",
        "",
        "class FieldSpec(NamedTuple):",
        "    key: str",
        "    domain: str",
        "    type: str",
        "    required: str",
        "    sensitivity: str",
        "    cardinality: str",
        "    rollup: bool",
        "    action: str",
        "    enum: tuple[str, ...]",
        "",
        "",
        "class Ctx:",
        '    """Attribute keys, grouped by context domain."""',
    ]
    for dom in reg["domains"]:
        out.append("")
        out.append(f"    # -- {dom['domain']} ({dom['owner']})")
        for f in dom["fields"]:
            out.append(f"    {f['name']} = {f['key']!r}")
    out += ["", "", "class SpanName:", '    """Canonical span names (templated names use str.format)."""']
    for s in reg["spans"]["spans"]:
        out.append(f"    {s['op']} = {s['name']!r}")
    out += ["", "", "class Metric:", '    """Canonical metric instrument names."""']
    for m in reg["metrics"]:
        out.append(f"    {m['name']} = {m['key']!r}")
    out += ["", "", "REGISTRY: dict[str, FieldSpec] = {"]
    for f in fields.values():
        enum = tuple(str(e) for e in f.get("enum", []) or [])
        out.append(
            f"    {f['key']!r}: FieldSpec({f['key']!r}, {f['domain']!r}, {f['type']!r}, "
            f"{f['required']!r}, {f['sensitivity']!r}, {f['cardinality']!r}, "
            f"{bool(f['rollup'])!r}, {f['action']!r}, {enum!r}),"
        )
    out.append("}")
    sp = reg["spans"]
    out += ["", f"ENVELOPE: tuple[str, ...] = ({', '.join('Ctx.' + n for n in sp['envelope'])},)"]
    out += [f"RESOURCE_ATTRIBUTES: tuple[str, ...] = ({', '.join('Ctx.' + n for n in sp['resource'])},)"]
    out += [f"CANONICAL_CONTEXT: tuple[str, ...] = ({', '.join('Ctx.' + n for n in sp['canonical_context'])},)"]
    out += ["", "# operation -> attributes required on every span of that operation (envelope excluded)",
            "REQUIRED_ATTRIBUTES: dict[str, tuple[str, ...]] = {"]
    for s in sp["spans"]:
        req = ", ".join("Ctx." + n for n in s.get("required", []))
        out.append(f"    SpanName.{s['op']}: ({req}{',' if req else ''}),")
    out.append("}")
    out += ["", "SPAN_KINDS: dict[str, str] = {"]
    for s in sp["spans"]:
        out.append(f"    SpanName.{s['op']}: {s['kind']!r},")
    out.append("}")
    out += ["", "# action != keep, consumed by gernas.redaction on every attribute write",
            "REDACTION_ACTIONS: dict[str, str] = {"]
    for f in fields.values():
        if f["action"] != "keep":
            out.append(f"    Ctx.{f['name']}: {f['action']!r},")
    out.append("}")
    return "\n".join(out) + "\n"


_COLLECTOR_RULE = {
    "drop": "processors.attributes/pdpl delete",
    "fingerprint": "processors.attributes/pdpl hash",
    "mask": "processors.transform/pii_mask",
    "tokenise": "processors.attributes/pdpl hash (tokenisation service not provisioned - R3)",
    "keep": "processors.redaction allow-list",
}


def render_redaction_matrix(fields: dict[str, dict], version: str) -> str:
    rows = []
    for f in fields.values():
        rows.append({
            "field": f["key"], "domain": f["domain"], "sensitivity": f["sensitivity"],
            "action": f["action"], "cardinality": f["cardinality"], "rollup_dimension": bool(f["rollup"]),
            "collector_rule": _COLLECTOR_RULE[f["action"]],
            "notes": "PDPL: never leaves the process" if f["action"] == "drop" else "",
        })
    doc = {"version": version, "status": "DRAFT - pending CISO / Data Governance sign-off (risk R3)", "fields": rows}
    return "# AUTO-GENERATED by registry/generate.py - do not edit.\n" + yaml.safe_dump(doc, sort_keys=False, width=200)


_SEMCONV_TYPE = {"string": "string", "int": "int", "double": "double", "boolean": "boolean", "string[]": "string[]"}
_REQ_LEVEL = {"always": "required", "conditional": "conditionally_required", "never": "opt_in"}


def render_semconv(reg: dict, version: str) -> str:
    groups = []
    for dom in reg["domains"]:
        attrs = []
        for f in dom["fields"]:
            a = {"id": f["key"], "type": _SEMCONV_TYPE[f["type"]], "brief": f["brief"],
                 "requirement_level": _REQ_LEVEL[f["required"]], "stability": "development"}
            if f.get("enum"):
                a["type"] = {"members": [{"id": str(e), "value": str(e)} for e in f["enum"]]}
            if "example" in f:
                a["examples"] = [f["example"]] if not isinstance(f["example"], list) else f["example"]
            attrs.append(a)
        groups.append({"id": f"registry.gernas.{dom['domain']}", "type": "attribute_group",
                       "brief": dom["brief"], "attributes": attrs})
    for s in reg["spans"]["spans"]:
        groups.append({"id": f"span.gernas.{s['op'].lower()}", "type": "span", "span_kind": s["kind"].lower(),
                       "brief": f"{s['name']} emitted by {s['decorator']}",
                       "attributes": [{"ref": next(f["key"] for d in reg["domains"] for f in d["fields"] if f["name"] == n),
                                       "requirement_level": "required"} for n in s.get("required", [])]})
    doc = {"schema_url": f"https://gernas.fab/schemas/{version}", "groups": groups}
    return "# AUTO-GENERATED by registry/generate.py - do not edit.\n" + yaml.safe_dump(doc, sort_keys=False, width=200)


def render_reference(reg: dict, version: str) -> str:
    lines = [
        "<!-- AUTO-GENERATED by registry/generate.py - do not edit. -->",
        f"# GERNAS attribute reference (registry {version})",
        "",
        "Every attribute the Gernas SDK can emit. SDK code references these only through",
        "`gernas.Ctx`; the Collector allow-list and redaction matrix are generated from the same source.",
        "",
        "Legend: **req** always / conditional / never · **sens** sensitivity class · **card** cardinality class ·",
        "**rollup** may slice a report · **action** default PDPL action.",
        "",
    ]
    for i, dom in enumerate(reg["domains"], 1):
        lines += [f"## {i}. {dom['domain']} — owner: {dom['owner']}", "", dom["brief"], "",
                  "| Constant | Key | Type | req | sens | card | rollup | action | Example | Description |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for f in dom["fields"]:
            enum = f" (`{'`, `'.join(str(e) for e in f['enum'])}`)" if f.get("enum") else ""
            lines.append(f"| `Ctx.{f['name']}` | `{f['key']}` | {f['type']}{enum} | {f['required']} | {f['sensitivity']} | "
                         f"{f['cardinality']} | {'yes' if f['rollup'] else 'no'} | {f['action']} | `{f.get('example', '')}` | {f['brief']} |")
        lines.append("")
    lines += ["## Span catalogue", "", "| Operation | Span name | Decorator | Kind | Required attributes (plus envelope) |",
              "|---|---|---|---|---|"]
    for s in reg["spans"]["spans"]:
        lines.append(f"| `{s['op']}` | `{s['name']}` | `{s['decorator']}` | {s['kind']} | "
                     f"{', '.join('`' + n + '`' for n in s.get('required', [])) or '—'} |")
    lines += ["", f"Envelope (every span): {', '.join('`' + n + '`' for n in reg['spans']['envelope'])}", "",
              f"Canonical context checked by `gernas doctor` (13): {', '.join('`' + n + '`' for n in reg['spans']['canonical_context'])}",
              "", "## Metrics", "", "| Constant | Name | Type | Unit | Description |", "|---|---|---|---|---|"]
    for m in reg["metrics"]:
        lines.append(f"| `Metric.{m['name']}` | `{m['key']}` | {m['type']} | {m['unit']} | {m['brief']} |")
    return "\n".join(lines) + "\n"


def render_allowlist_block(fields: dict[str, dict], extra: dict, indent: str) -> str:
    keys = sorted({f["key"] for f in fields.values() if f["action"] != "drop"} | set(extra.get("allowed_keys", [])))
    body = [indent + ALLOW_BEGIN] + [f"{indent}- {k}" for k in keys] + [indent + ALLOW_END]
    return "\n".join(body)


def apply_allowlist(config_text: str, block_renderer) -> str:
    lines = config_text.splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == ALLOW_BEGIN)
        end = next(i for i, l in enumerate(lines) if l.strip() == ALLOW_END)
    except StopIteration:
        return config_text
    indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
    new = lines[:start] + block_renderer(indent).splitlines() + lines[end + 1:]
    return "\n".join(new) + ("\n" if config_text.endswith("\n") else "")


def build_outputs() -> dict[Path, str]:
    reg = load()
    fields = validate(reg)
    version = str(reg["spans"].get("version", "2026.10.0"))
    outputs = {
        ROOT / "gernas" / "attributes.py": render_attributes(reg, fields, version),
        REGISTRY / "redaction-matrix.yaml": render_redaction_matrix(fields, version),
        REGISTRY / "semantic-conventions.yaml": render_semconv(reg, version),
        ROOT / "docs" / "attribute-reference.md": render_reference(reg, version),
    }
    for cfg in sorted((ROOT / "collector").glob("*.yaml")):
        text = cfg.read_text(encoding="utf-8")
        if ALLOW_BEGIN in text:
            outputs[cfg] = apply_allowlist(text, lambda ind: render_allowlist_block(fields, reg["extra"], ind))
    return outputs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any generated artefact is out of date")
    args = ap.parse_args(argv)
    try:
        outputs = build_outputs()
    except RegistryError as exc:
        print(exc, file=sys.stderr)
        return 2
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    rel = [str(p.relative_to(ROOT)) for p in stale]
    if args.check:
        if stale:
            print("Stale generated artefacts (run `python registry/generate.py`):\n  " + "\n  ".join(rel), file=sys.stderr)
            return 1
        print("registry: all generated artefacts up to date")
        return 0
    print(f"registry: {len(outputs)} artefacts checked, {len(stale)} written" + (": " + ", ".join(rel) if rel else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
