"""Generate every registry-derived artefact from ``registry/domains/*.yaml``.

The attribute registry is the contract (WP1-CTX-01/02). Nothing downstream is
maintained by hand:

    gernas/attributes.py              Ctx / SpanName / Metric constants + REGISTRY
    registry/redaction-matrix.yaml    one row per field (WP1-CTX-05)
    registry/semantic-conventions.yaml  OTel-semconv-style groups for non-Python services
    docs/attribute-reference.md       16-domain attribute reference (WP1-DOCS-01 step 2)
    collector/otel-collector-config.yaml  allow-list block between GERNAS-ALLOWLIST markers

Usage::

    python registry/generate.py           # validate + write
    python registry/generate.py --check   # validate + fail if any artefact is stale (CI)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "registry"
DOMAINS_DIR = REGISTRY / "domains"

REQUIRED_PROPS = ("name", "key", "type", "required", "sensitivity", "cardinality", "rollup", "action", "brief")
ENUMS = {
    "type": {"string", "int", "double", "boolean", "string[]"},
    "required": {"always", "conditional", "never"},
    "sensitivity": {"public", "internal", "confidential", "restricted", "secret"},
    "cardinality": {"bounded", "growing", "unbounded"},
    "action": {"keep", "fingerprint", "mask", "tokenise", "drop"},
}
SPAN_KINDS = {"INTERNAL", "SERVER", "CLIENT", "PRODUCER", "CONSUMER"}
ALLOW_BEGIN = "# >>> GERNAS-ALLOWLIST (generated by registry/generate.py - do not edit)"
ALLOW_END = "# <<< GERNAS-ALLOWLIST"


class RegistryError(ValueError):
    pass


def load() -> dict:
    domains = []
    for path in sorted(DOMAINS_DIR.glob("*.yaml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        doc["_file"] = path.name
        domains.append(doc)
    spans = yaml.safe_load((REGISTRY / "spans.yaml").read_text(encoding="utf-8"))
    metrics = yaml.safe_load((REGISTRY / "metrics.yaml").read_text(encoding="utf-8"))
    extra = yaml.safe_load((REGISTRY / "collector-allowlist-extra.yaml").read_text(encoding="utf-8"))
    return {"domains": domains, "spans": spans, "metrics": metrics["metrics"], "extra": extra}


def validate(reg: dict) -> dict[str, dict]:
    errors: list[str] = []
    fields: dict[str, dict] = {}
    keys: dict[str, str] = {}
    for dom in reg["domains"]:
        for prop in ("domain", "owner", "brief", "fields"):
            if prop not in dom:
                errors.append(f"{dom['_file']}: missing domain property '{prop}'")
        for f in dom.get("fields", []):
            label = f"{dom['_file']}:{f.get('name', '?')}"
            for prop in REQUIRED_PROPS:
                if prop not in f:
                    errors.append(f"{label}: missing property '{prop}'")
            for prop, allowed in ENUMS.items():
                if prop in f and f[prop] not in allowed:
                    errors.append(f"{label}: {prop}={f[prop]!r} not in {sorted(allowed)}")
            if f.get("name") in fields:
                errors.append(f"{label}: duplicate constant name")
            if f.get("key") in keys:
                errors.append(f"{label}: duplicate key {f['key']} (also {keys[f['key']]})")
            if f.get("cardinality") == "unbounded" and f.get("rollup"):
                errors.append(f"{label}: unbounded field cannot be a rollup dimension (WP1-CTX-06)")
            if f.get("sensitivity") in ("restricted", "secret") and f.get("action") == "keep":
                errors.append(f"{label}: {f['sensitivity']} field must not use action=keep (PDPL)")
            f = dict(f, domain=dom.get("domain"))
            fields[f["name"]] = f
            keys[f["key"]] = label
    spans = reg["spans"]
    for group in ("envelope", "resource", "canonical_context"):
        for name in spans.get(group, []):
            if name not in fields:
                errors.append(f"spans.yaml:{group}: unknown field {name}")
    if len(spans.get("canonical_context", [])) != 13:
        errors.append("spans.yaml: canonical_context must list exactly 13 fields")
    ops = set()
    for s in spans["spans"]:
        if s["op"] in ops:
            errors.append(f"spans.yaml: duplicate op {s['op']}")
        ops.add(s["op"])
        if s.get("kind") not in SPAN_KINDS:
            errors.append(f"spans.yaml:{s['op']}: bad kind {s.get('kind')}")
        for name in s.get("required", []):
            if name not in fields:
                errors.append(f"spans.yaml:{s['op']}: unknown required field {name}")
    mnames = set()
    for m in reg["metrics"]:
        if m["name"] in mnames:
            errors.append(f"metrics.yaml: duplicate metric {m['name']}")
        mnames.add(m["name"])
    if len(reg["domains"]) != 16:
        errors.append(f"expected 16 domains, found {len(reg['domains'])} (risk R5: 13 vs 16)")
    if errors:
        raise RegistryError("Registry validation failed:\n  " + "\n  ".join(errors))
    return fields


